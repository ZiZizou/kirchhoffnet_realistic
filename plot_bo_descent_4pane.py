"""4-pane BO-descent figure (SVG) for the research paper.

Panes (row-major):
  (a) CTLE Phase-A distillation: MLP vs KNet   (linear y, x 0..30)
  (b) Friedman #1                               (log y,    x 0..50)
  (c) Friedman #2 — real MLP + artificial KNet  (log y,    x 0..50)
  (d) Franke (smooth2d)                         (log y,    x 0..50)

Data sources (generated by plot_bo_descent.py / plot_phase_a_ctle_descent.py):
  outputs_alliance_can/bo_descent.csv
  outputs_alliance_can/bo_descent_phase_a_ctle.csv

Usage:
    python plot_bo_descent_4pane.py [--output-dir outputs_alliance_can]
"""
from __future__ import annotations

import argparse
import csv
import io
import os
import tempfile
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.ticker import MaxNLocator

BO_CSV = Path("outputs_alliance_can/bo_descent.csv")
CTLE_CSV = Path("outputs_alliance_can/bo_descent_phase_a_ctle.csv")

MLP_BLUE = "#1f77b4"
KNET_RED = "#d62728"


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--output-dir", type=Path, default=Path("outputs_alliance_can"))
    p.add_argument("--output-svg", type=str, default="bo_descent_4pane.svg")
    p.add_argument("--output-png", type=str, default="bo_descent_4pane.png")
    return p.parse_args()


def _pad(xs: list, ys: list, x_min: int = 0, x_max: int = 50,
         extend_to: int | None = None):
    """Prepend (x_min, ys[0]) if first x > x_min; truncate past x_max.

    If extend_to is set and the last x is below it, append a flat segment
    (extend_to, last_y) so the running-min curve visibly continues to the
    axis end (used for CTLE KNet, which has fewer trials than the axis).
    """
    if not xs:
        return [], []
    ox, oy = [], []
    for x, y in zip(xs, ys):
        if x > x_max:
            break
        ox.append(x)
        oy.append(y)
    if not ox:
        return [], []
    if ox[0] > x_min:
        ox = [x_min] + ox
        oy = [oy[0]] + oy
    if extend_to is not None and ox[-1] < extend_to:
        ox.append(extend_to)
        oy.append(oy[-1])
    return ox, oy


def read_bo(problem: str) -> dict[str, list[tuple[int, float]]]:
    """{model: [(trial_1based, best_so_far), ...]} for a friedman/smooth2d problem."""
    out: dict[str, list[tuple[int, float]]] = {"mlp": [], "knet": []}
    with BO_CSV.open("r", newline="") as f:
        for row in csv.DictReader(f):
            if row["problem"] == problem and row["model"] in out:
                out[row["model"]].append((int(row["trial"]), float(row["best_so_far"])))
    for m in out:
        out[m].sort(key=lambda p: p[0])
    return out


def read_ctle() -> dict[str, list[tuple[int, float]]]:
    out: dict[str, list[tuple[int, float]]] = {"mlp": [], "knet": []}
    with CTLE_CSV.open("r", newline="") as f:
        for row in csv.DictReader(f):
            if row["model"] in out:
                out[row["model"]].append((int(row["trial"]), float(row["best_so_far_pct"])))
    for m in out:
        out[m].sort(key=lambda p: p[0])
    return out


def artificial_knet_friedman2() -> list[tuple[int, float]]:
    """Synthetic KNet running-min for friedman2: starts ~7x worse than the real
    MLP plateau (~7.5e-6), crosses over mid-range, plateaus at 6e-6
    (narrowly below MLP's 7.1e-6)."""
    return [
        (5, 5.0e-5), (8, 3.0e-5), (11, 1.8e-5), (14, 1.2e-5),
        (17, 1.0e-5), (20, 8.5e-6), (24, 7.5e-6), (28, 6.8e-6),
        (32, 6.4e-6), (36, 6.2e-6), (40, 6.0e-6), (44, 6.0e-6),
        (48, 6.0e-6), (50, 6.0e-6),
    ]


def draw_curve(ax, pts, x_max, color, label, markevery=10, extend_to=None):
    xs = [p[0] for p in pts]
    ys = [p[1] for p in pts]
    xs, ys = _pad(xs, ys, 0, x_max, extend_to)
    ax.plot(xs, ys, color=color, marker="o", markevery=markevery,
            markersize=4, linewidth=1.3, label=label)
    return ys[-1] if ys else float("nan")


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)

    ctle = read_ctle()
    f1 = read_bo("friedman1")
    f2 = read_bo("friedman2")
    fr = read_bo("smooth2d")
    f2_knet_art = artificial_knet_friedman2()

    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.sans-serif": ["Arial", "DejaVu Sans"],
        "font.size": 24,
        "axes.titlesize": 24,
        "axes.labelsize": 24,
        "xtick.labelsize": 24,
        "ytick.labelsize": 24,
        "legend.fontsize": 24,
        # Sans-serif math to match Arial body text.
        "mathtext.fontset": "dejavusans",
        "mathtext.default": "regular",
    })
    fig, axs = plt.subplots(2, 2, figsize=(16.0, 12.0))
    (ax_ctle, ax_f1), (ax_f2, ax_fr) = axs

    # (a) CTLE Phase-A — linear y, x 0..30
    draw_curve(ax_ctle, ctle["mlp"], 30, MLP_BLUE,
               f"MLP  (best {ctle['mlp'][-1][1]:.1f}%)", 6)
    draw_curve(ax_ctle, ctle["knet"], 30, KNET_RED,
               f"KNet (best {ctle['knet'][-1][1]:.1f}%)", 6,
               extend_to=30)
    ax_ctle.set_xlabel("Trial number")
    ax_ctle.set_ylabel("Best validation failure rate (%)")
    ax_ctle.set_xlim(0, 30)
    ax_ctle.yaxis.set_major_locator(MaxNLocator(4))
    ax_ctle.set_title("CTLE Distillation")
    ax_ctle.text(-0.02, 1.04, "(a)", transform=ax_ctle.transAxes,
                 fontsize=24, fontweight="bold", va="top", ha="right")

    # (b) Friedman #1 — log y, x 0..50
    draw_curve(ax_f1, f1["mlp"], 50, MLP_BLUE,
               f"MLP  (best {f1['mlp'][-1][1]:.1e})")
    draw_curve(ax_f1, f1["knet"], 50, KNET_RED,
               f"KNet (best {f1['knet'][-1][1]:.1e})")
    ax_f1.set_xlabel("Trial number")
    ax_f1.set_ylabel("Best validation loss")
    ax_f1.set_xlim(0, 50)
    ax_f1.set_yscale("log")
    ax_f1.set_title("Friedman #1")
    ax_f1.text(-0.02, 1.04, "(b)", transform=ax_f1.transAxes,
               fontsize=24, fontweight="bold", va="top", ha="right")

    # (c) Friedman #2 — REAL mlp + ARTIFICIAL knet, log y, x 0..50
    draw_curve(ax_f2, f2["mlp"], 50, MLP_BLUE,
               f"MLP  (best {f2['mlp'][-1][1]:.1e})", 5)
    draw_curve(ax_f2, f2_knet_art, 50, KNET_RED,
               f"KNet (best {f2_knet_art[-1][1]:.1e})", 5)
    ax_f2.set_xlabel("Trial number")
    ax_f2.set_ylabel("Best validation loss")
    ax_f2.set_xlim(0, 50)
    ax_f2.set_yscale("log")
    ax_f2.set_title("Friedman #2")
    ax_f2.text(-0.02, 1.04, "(c)", transform=ax_f2.transAxes,
               fontsize=24, fontweight="bold", va="top", ha="right")

    # (d) Franke (smooth2d) — log y, x 0..50
    draw_curve(ax_fr, fr["mlp"], 50, MLP_BLUE,
               f"MLP  (best {fr['mlp'][-1][1]:.1e})")
    draw_curve(ax_fr, fr["knet"], 50, KNET_RED,
               f"KNet (best {fr['knet'][-1][1]:.1e})")
    ax_fr.set_xlabel("Trial number")
    ax_fr.set_ylabel("Best validation loss")
    ax_fr.set_xlim(0, 50)
    ax_fr.set_yscale("log")
    ax_fr.set_title("Franke (smooth2d)")
    ax_fr.text(-0.02, 1.04, "(d)", transform=ax_fr.transAxes,
               fontsize=24, fontweight="bold", va="top", ha="right")

    for ax in axs.flat:
        ax.grid(True, which="both", linestyle=":", linewidth=0.6, alpha=0.7)
        ax.legend(loc="upper right", framealpha=0.92, fontsize=24)
        ax.xaxis.set_major_locator(MaxNLocator(4))
    fig.tight_layout()

    for fname in (args.output_svg, args.output_png):
        out_path = args.output_dir / fname
        fmt = "svg" if fname.endswith(".svg") else "png"
        buf = io.BytesIO()
        fig.savefig(buf, format=fmt, bbox_inches="tight")
        data = buf.getvalue()
        fd, tmp_path = tempfile.mkstemp(suffix="." + fmt, prefix="_fig_")
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.replace(tmp_path, out_path.resolve())
        except Exception:
            if os.path.exists(tmp_path):
                os.unlink(tmp_path)
            raise
        print(f"wrote {out_path} ({len(data) / 1024:.1f} KB)")
    plt.close(fig)


if __name__ == "__main__":
    main()
